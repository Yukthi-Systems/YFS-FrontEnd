// Converts a lowercase ISO 3166-1 alpha-2 code to its Unicode flag emoji (two Regional
// Indicator Symbol letters — "in" -> 🇮🇳). Renders as a real flag glyph on most
// modern platforms; falls back to the two letters themselves on ones that don't have
// the flag glyphs (older Windows), which is still legible.
export const flagEmoji = (iso2: string): string =>
  iso2
    .toUpperCase()
    .replace(/./g, (c) => String.fromCodePoint(127397 + c.charCodeAt(0)));
